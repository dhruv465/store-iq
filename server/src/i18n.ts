const TABLES: Record<Lang, Record<string, Phrase>> = { en: EN, hi: HI, mr: MR };
/** Exported so a test can hold the three tables to each other: a phrase missing from one is a
 *  sentence of English dropped into the middle of a Hindi conversation. */
export const PHRASES = TABLES;

/** English is the fallback, so a phrase missing in one language degrades instead of breaking. */
/** A card value in the associate's language, falling back to the value itself when it is free text. */
export function v(lang: Lang, value: string): string {
  const key = `v.${value}`;
  const table = TABLES[lang] ?? EN;
  const phrase = table[key] ?? EN[key];
  return typeof phrase === "string" ? phrase : value;
}

export function t(lang: Lang, key: string, vars: Record<string, string | number> = {}): string {
  const phrase = TABLES[lang]?.[key] ?? EN[key];
  if (phrase === undefined) return key;
  return typeof phrase === "function" ? phrase(vars) : phrase;
}

const EXPLICIT: [RegExp, Lang][] = [
  [/\b(english|angrezi|इंग्लिश|इंग्रजी)\b/i, "en"],
  [/\b(marathi|मराठी)\b/i, "mr"],
  [/\b(hindi|हिंदी|हिन्दी)\b/i, "hi"],
];

/** An explicit request wins. Otherwise Devanagari means Hindi, since both scripts look alike. */
export function languageFrom(text: string | undefined, current: Lang): Lang {
  if (!text) return current;
  for (const [pattern, lang] of EXPLICIT) if (pattern.test(text)) return lang;
  if (/[ऀ-ॿ]/.test(text)) return current === "mr" ? "mr" : "hi";
  // Latin script keeps whatever was chosen: Hinglish and Marathi in Latin are still that language.
  return current;
}

export function askedToSwitchLanguage(text: string | undefined): Lang | null {
  if (!text) return null;
  for (const [pattern, lang] of EXPLICIT) if (pattern.test(text)) return lang;
  return null;
}
